"""One canonical shop per vertical, rendered to a stable prompt.

The snapshot test and `scripts/snapshot_prompts.py` both import from here so
there is exactly one definition of what a snapshot is. If the two ever drifted,
the test would be checking a different prompt from the one the script writes,
which is the one failure mode a snapshot suite must not have.

The fixture deliberately fills in price ranges, FAQs, business info and handoff
notes. A shop straight out of `new_shop_config` leaves those empty, and the
sections would render "(not configured)" - so a regression in `_price_lines` or
`_faq_lines` would slip past unnoticed.
"""

from __future__ import annotations

from typing import Any

from app.agent.prompt import build_system_prompt
from app.core.defaults import VERTICALS, new_shop_config

#: Sorted so the rendered file cannot move when the enum's order changes.
CHANNELS: tuple[str, ...] = ("simulator", "sms", "voice", "whatsapp")

#: Every vertical, sorted. The snapshot set is the whole matrix on purpose: a
#: per-niche prompt change that leaks into another vertical shows up as a diff
#: in a file nobody meant to touch.
def vertical_keys() -> tuple[str, ...]:
    return tuple(sorted(VERTICALS))


def snapshot_shop(vertical: str) -> dict[str, Any]:
    """A fully-populated shop for one vertical. No clocks, no randomness."""
    config = new_shop_config(vertical=vertical)
    config["business_info"] = {
        "address": "1 Example Street",
        "payment": "Card or cash",
        "phone": "+10000000000",
    }
    config["price_ranges"] = [
        {"service": "Example service", "low": 100, "high": 200},
    ]
    config["faqs"] = [
        {"q": "Do you take walk-ins?", "a": "Yes, when we have a free slot."},
    ]
    config["handoff_rules"]["notes"] = "Anything unusual comes to me first."
    config["tone"] = "Friendly, brief and practical. Never pushy."
    return {
        "name": "Snapshot Shop",
        "timezone": "America/Chicago",
        "config": config,
    }


def render(vertical: str) -> str:
    """The snapshot body for one vertical: every channel, in a fixed order."""
    shop = snapshot_shop(vertical)
    parts = [
        f"# snapshot: vertical={vertical}",
        "#",
        "# Generated by scripts/snapshot_prompts.py --update.",
        "# A diff here is a prompt change. Read it before you accept it.",
    ]
    for channel in CHANNELS:
        parts += [
            "",
            f"{'=' * 72}",
            f"=== channel: {channel}",
            f"{'=' * 72}",
            "",
            build_system_prompt(shop, channel),
        ]
    return "\n".join(parts) + "\n"
